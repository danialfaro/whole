// Precompute the board chosen for each classic level and write js/core/levels.js.
// Run after changing LEVEL_PLAN, buildBoard or the difficulty measure:
//
//   node tools/build-levels.mjs [levels=100] [tries=1500]
//
// Prints the resulting difficulty curve. "check" re-measures the chosen board
// with an independent seed and more runs: that is the honest difficulty (the
// "stuck" column is slightly optimistic because it is the best of many tries).
// Not a build step: without the table the game searches each level at runtime
// (fewer candidates).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { pickBoard, buildBoard, targetOf } from "../js/core/generate.js";
import { solveAll, pop } from "../js/core/geometry.js";
import { stuckRate } from "../js/core/difficulty.js";

const levels = +(process.argv[2] ?? 100),
  tries = +(process.argv[3] ?? 1500);
const salts = [],
  pct = (x) => String(Math.round(x * 100)).padStart(4) + "%";

console.log("level pieces  target  stuck  check  sizes        salt");
const t0 = Date.now();
let worst = 0;
for (let n = 1; n <= levels; n++) {
  const best = pickBoard(n, tries);
  const board = buildBoard(n, best.salt);
  if (!solveAll(board)) throw new Error(`level ${n}: board is not solvable`);
  salts.push(best.salt);
  const check = stuckRate(board, 424242 + n, 600);
  worst = Math.max(worst, Math.abs(check - targetOf(n)));
  const sizes = [...new Set(board.map((p) => pop(p.mask)))].sort().join("/");
  console.log(
    String(n).padStart(5),
    String(board.length).padStart(6),
    pct(targetOf(n)).padStart(7),
    pct(best.rate).padStart(6),
    pct(check).padStart(6),
    " " + sizes.padEnd(12),
    best.salt,
  );
}

const out = fileURLToPath(new URL("../js/core/levels.js", import.meta.url));
writeFileSync(
  out,
  `// Generated by \`node tools/build-levels.mjs\`. Do not edit by hand.\n` +
    `// Salt of the board chosen for each classic level (index 0 = level 1).\n` +
    `// prettier-ignore\n` +
    `export const LEVEL_SALTS = [${salts.join(", ")}];\n`,
);
console.log(`\nworst |check - target| = ${pct(worst).trim()}`);
console.log(`wrote ${levels} levels to js/core/levels.js in ${Math.round((Date.now() - t0) / 1000)}s`);
